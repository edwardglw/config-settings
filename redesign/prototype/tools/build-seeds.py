#!/usr/bin/env python3
"""Regenerate seeds-data.js from the source images.

The prototype inlines its eight starting images as data URLs. That is not
an optimisation: a page opened from file:// cannot call getImageData on a
canvas that has drawn a local file, because the canvas is tainted. Data
URLs are same-origin, so the analysis runs with no server and no flags.

Usage:  python3 tools/build-seeds.py [source-dir]
Default source-dir is ../../../../baseimages
"""
import base64, io, os, sys
from PIL import Image

NAMES = ['10dark','blackdashboard','blueredrun','bluescreensplash',
         'brightsquare','goast','goldlake','poster100']
MAX, QUALITY = 620, 80

here = os.path.dirname(os.path.abspath(__file__))
proto = os.path.dirname(here)
src_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.join(proto, '..', '..', '..', 'baseimages')

lines = ["/* Seed images inlined as data URLs — generated by tools/build-seeds.py.",
         "   Data URLs keep the canvas untainted so the prototype works from file://",
         "   with no server. Do not hand-edit. */",
         "const SEED_DATA = {"]
for n in NAMES:
    path = next((os.path.join(src_dir, n + e) for e in ('.png','.jpg','.jpeg')
                 if os.path.exists(os.path.join(src_dir, n + e))), None)
    if not path:
        print(f'  ! missing {n}', file=sys.stderr); continue
    im = Image.open(path).convert('RGB')
    im.thumbnail((MAX, MAX), Image.LANCZOS)
    buf = io.BytesIO(); im.save(buf, 'JPEG', quality=QUALITY, optimize=True)
    b64 = base64.b64encode(buf.getvalue()).decode()
    lines.append(f"  '{n}': 'data:image/jpeg;base64,{b64}',")
    print(f'  {n:20} {im.size[0]}x{im.size[1]}  {len(b64)//1024} KB')
lines.append("};")

out = os.path.join(proto, 'seeds-data.js')
open(out, 'w').write('\n'.join(lines))
print(f'\nwrote {out} ({os.path.getsize(out)//1024} KB)')
